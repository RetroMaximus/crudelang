"""Projects: the manifest, its resources, and the pipeline that loads them.

The layers, bottom up:

* :mod:`crude.project.manifest` - ``crude.manifest.json`` as frozen dataclasses,
  validated strictly and pointing at the exact key that is wrong;
* :mod:`crude.project.resources` - the file table the manifest describes, with
  array files parsed into numbers and presets read and written;
* :mod:`crude.project.progress` - the load plan, one weighted step per phase, and
  the reporters that tell the user about them;
* :mod:`crude.project.loader` - ``Project`` and ``LoadPipeline``: the fixed phase
  order that turns a directory into a running host, unwinding in reverse when a
  phase fails.

Nothing here opens a window or a device: the loader asks the audio and Pd
runtimes to do that, and every phase is testable against their fakes.
"""

