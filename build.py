#!/usr/bin/env python3
"""Build the ``crude`` command line into a standalone executable with PyInstaller.

One script for Windows, Linux and macOS. It does two jobs in order:

1. **Make sure the platform's ``libpd`` shared library is in ``libs/``.** The
   runtime (:mod:`crude.pd.lib`) loads ``libpd.dll`` / ``libpd.so`` /
   ``libpd.dylib`` through :func:`ctypes.CDLL`, and looks for it - in order -
   under ``$CRUDE_LIBPD_PATH``, the repo ``libs/`` directory, a PyInstaller
   bundle and the current directory. If ``libs/`` does not already hold the
   right file this script searches the common places a libpd might already be
   installed (MSYS2, a Pure Data install, Homebrew, system library dirs, a
   ``third-party/libpd`` build) and copies it - and, on Windows, the MinGW
   runtime DLLs it links against - into ``libs/``. If nothing is found it stops
   with the exact command to build libpd from source; it never downloads.

2. **Run PyInstaller.** The whole ``crude`` package is collected and everything
   in ``libs/`` is bundled as *data binaries* under a ``libs/`` prefix, so a
   frozen build reads the same layout :func:`crude.pd.lib.dll_bootstrap` uses
   on a development checkout (``sys._MEIPASS/libs/libpd.dll``).

After a build it can smoke-test the result (``--verify`` runs the new binary's
``--version``) to prove the bundle at least starts and can reach its libraries.

Examples
--------
    python build.py                       # current platform, one-dir bundle
    python build.py --onefile             # a single self-contained executable
    python build.py --libpd ./mine.so     # use this libpd instead of searching
    python build.py --dry-run             # print the plan, build nothing
    python build.py --verify              # build, then run the exe --version
    python build.py --skip-libs           # assume libs/ is already correct

Run it with the interpreter that has the dependencies installed (the project
virtual environment), where ``pip install -r requirements-dev.txt`` has already
put ``pyinstaller`` on the path.
"""

from __future__ import annotations

import argparse
import glob
import os
import shutil
import subprocess
import sys
from pathlib import Path

# --------------------------------------------------------------------------
# repository layout
# --------------------------------------------------------------------------

ROOT = Path(__file__).resolve().parent
LIBS_DIR = ROOT / "libs"
ENTRY = ROOT / "crude" / "__main__.py"          # documented entry of the package
DIST = ROOT / "dist"
BUILD = ROOT / "build"
EXE_NAME = "crude"

# PyInstaller freezes the file you point it at as a top-level ``__main__``, so a
# script that uses *relative* imports (``from .cli import main``) blows up at
# launch with "attempted relative import with no known parent package". We
# therefore generate a one-line launcher that imports the package by absolute
# name and hand that to PyInstaller instead of ``crude/__main__.py``. It lives
# outside the PyInstaller work dir so ``--clean`` never wipes the input script.
LAUNCHER_DIR = ROOT / ".build_entry"
LAUNCHER = LAUNCHER_DIR / "crude_build_entry.py"
LAUNCHER_SOURCE = '''"""Generated by build.py - PyInstaller entry point for the crude CLI."""
import sys

from crude.cli import main

if __name__ == "__main__":
    sys.exit(main())
'''

# the shared-library file name we look for on each platform, matching
# crude/pd/lib.py:_candidate_paths() exactly
LIB_NAMES = {
    "windows": "libpd.dll",
    "linux": "libpd.so",
    "darwin": "libpd.dylib",
}

# On Windows libpd is a MinGW build that links against a small runtime; without
# these beside it ctypes raises "The specified module could not be found" even
# though libpd.dll itself is there. We copy any of these found next to a located
# libpd.dll. (Prefixes, matched case-insensitively - the numeric suffixes move
# between toolchain versions.)
WIN_RUNTIME_PREFIXES = (
    "libstdc++", "libc++", "libunwind", "libwinpthread", "libgcc",
    "libgfortran", "portaudio", "pd",
)

IS_WINDOWS = sys.platform.startswith("win")


def current_platform() -> str:
    """Map ``sys.platform`` onto the three names this script understands."""
    if sys.platform.startswith("win"):
        return "windows"
    if sys.platform == "darwin":
        return "darwin"
    if sys.platform.startswith("linux"):
        return "linux"
    # fall back to the closest thing so the message is still useful
    return "linux"


# --------------------------------------------------------------------------
# locating an already-installed libpd
# --------------------------------------------------------------------------

def _program_files() -> list[Path]:
    """The Windows Program Files roots, whichever drive they live on."""
    roots = []
    for env in ("ProgramFiles", "ProgramFiles(x86)", "ProgramW6432",
                "LOCALAPPDATA"):
        value = os.environ.get(env)
        if value:
            roots.append(Path(value))
    return roots


def search_dirs(platform: str) -> list[Path]:
    """Candidate directories that plausibly already hold a libpd, in priority
    order. Deliberately a bounded, hand-picked list rather than a whole-disk
    walk: fast, predictable, and it never reaches into unrelated user files."""
    dirs: list[Path] = []

    # a from-source build drops libpd here first (see scripts/*.sh)
    dirs += [
        ROOT / "third-party" / "libpd" / "libs",
        ROOT / "third-party" / "libpd",
        ROOT / "third-party",
    ]

    if platform == "windows":
        # MSYS2 / MinGW toolchains (the ones scripts/pd_dll_build.sh use)
        for drive in ("C:\\", "D:\\"):
            for env in ("ucrt64", "mingw64", "clang64", "msys64"):
                dirs.append(Path(drive) / "msys64" / env / "bin")
        dirs.append(Path("C:\\msys64\\usr\\bin"))
        # a Pure Data / libpd install
        for base in _program_files():
            for pattern in ("Pure Data*", "Programs/Pure Data*", "libpd*"):
                dirs += [Path(m) for m in glob.glob(str(base / pattern))]
        # anywhere already on PATH
        for entry in os.environ.get("PATH", "").split(os.pathsep):
            if entry:
                dirs.append(Path(entry))

    elif platform == "darwin":
        dirs += [
            Path("/opt/homebrew/lib"),            # Apple Silicon Homebrew
            Path("/usr/local/lib"),               # Intel Homebrew / manual
            Path("/usr/local/opt/libpd/lib"),
            Path.home() / "Library" / "Frameworks",
        ]
        # a Pd.app bundle keeps its libraries under Resources
        for pattern in ("/Applications/Pd*.app/Contents/Resources/lib",
                        "/Applications/Pd*.app/Contents/Resources/bin",
                        "/Applications/Pd*.app/Contents/Frameworks"):
            dirs += [Path(m) for m in glob.glob(pattern)]

    else:  # linux
        dirs += [
            Path("/usr/local/lib"),
            Path("/usr/lib"),
            Path("/usr/lib/x86_64-linux-gnu"),
            Path("/usr/lib64"),
            Path("/lib"),
            Path("/lib/x86_64-linux-gnu"),
            Path.home() / ".local" / "lib",
            Path("/usr/local/lib/pd"),
            Path("/usr/lib/pd/lib"),
        ]
        # a conda environment, if one is active
        prefix = os.environ.get("CONDA_PREFIX")
        if prefix:
            dirs.append(Path(prefix) / "lib")

    # de-duplicate, keep order, drop anything that does not exist
    seen: set[str] = set()
    out: list[Path] = []
    for d in dirs:
        key = str(d).lower() if IS_WINDOWS else str(d)
        if key in seen:
            continue
        seen.add(key)
        if d.is_dir():
            out.append(d)
    return out


def find_installed_libpd(platform: str) -> Path | None:
    """First libpd found in the search dirs, or ``None``."""
    name = LIB_NAMES[platform]
    for directory in search_dirs(platform):
        candidate = directory / name
        if candidate.is_file():
            return candidate
        # a from-source build may leave it named pd.dll / with a version suffix
        for extra in glob.glob(str(directory / f"{name.split('.')[0]}*")):
            p = Path(extra)
            if p.is_file() and p.name == name:
                return p
    return None


def _runtime_siblings(source: Path, platform: str) -> list[Path]:
    """MinGW runtime DLLs that live next to ``source`` and must travel with it.
    Only meaningful on Windows; empty elsewhere (ELF/Mach-O resolve their own
    dependencies from system paths)."""
    if platform != "windows":
        return []
    found: list[Path] = []
    for dll in source.parent.glob("*.dll"):
        low = dll.name.lower()
        if dll == source:
            continue
        if any(low.startswith(prefix) for prefix in WIN_RUNTIME_PREFIXES):
            found.append(dll)
    return found


def ensure_library(platform: str, override: str | None, *, skip: bool,
                   quiet: bool = False) -> Path:
    """Guarantee ``libs/<libpd>`` exists for ``platform``; return its path.

    ``override`` is an explicit path the user pointed at. ``skip`` means "leave
    libs/ exactly as it is" (used when the operator already staged the library).
    Raises ``SystemExit`` with build-from-source guidance when nothing is found.
    """
    target = LIBS_DIR / LIB_NAMES[platform]

    def log(msg: str) -> None:
        if not quiet:
            print(msg)

    if skip:
        log(f"[libs] --skip-libs: using libs/ as it is ({target.name}).")
        return target if target.exists() else LIBS_DIR

    LIBS_DIR.mkdir(parents=True, exist_ok=True)

    # already staged correctly -> nothing to do
    if target.is_file() and not override:
        log(f"[libs] found {LIB_NAMES[platform]} already in libs/.")
        return target

    # decide where the library comes from
    source: Path | None
    if override:
        source = Path(override).expanduser().resolve()
        if not source.exists():
            sys.exit(f"[libs] --libpd path does not exist: {source}")
        if source.is_dir():
            source = source / LIB_NAMES[platform]
            if not source.is_file():
                sys.exit(f"[libs] no {LIB_NAMES[platform]} in directory {override}")
    else:
        source = find_installed_libpd(platform)

    if source is None:
        sys.exit(
            "[libs] could not find "
            f"{LIB_NAMES[platform]} in libs/ or any common install location.\n"
            "       Build it from source and it will be picked up automatically:\n"
            "         Windows (MSYS2):  bash scripts/pd_dll_build.sh\n"
            "         Linux / macOS:    bash scripts/libpd_build.sh\n"
            "       ...or point the build at an existing copy:\n"
            f"         python build.py --libpd /path/to/{LIB_NAMES[platform]}\n"
            f"       (or set $CRUDE_LIBPD_PATH to that file or its directory)."
        )

    # copy the library and, on Windows, its runtime siblings into libs/
    copied = [target]
    if source != target:
        shutil.copy2(source, target)
        log(f"[libs] copied {source} -> {target}")
    for sib in _runtime_siblings(source, platform):
        dest = LIBS_DIR / sib.name
        if not dest.exists():
            shutil.copy2(sib, dest)
            copied.append(dest)
            log(f"[libs] copied runtime sibling {sib.name} -> libs/")

    return target


# --------------------------------------------------------------------------
# the PyInstaller invocation
# --------------------------------------------------------------------------

def _bundle_files(platform: str) -> list[Path]:
    """Everything in libs/ that should travel inside the executable."""
    patterns = {
        "windows": ("*.dll",),
        "linux": ("*.so", "*.so.*"),
        "darwin": ("*.dylib",),
    }[platform]
    files: list[Path] = []
    for pattern in patterns:
        files += [Path(p) for p in glob.glob(str(LIBS_DIR / pattern))]
    return sorted(set(files))


def build_command(platform: str, *, onefile: bool, add_libs: list[Path],
                  clean: bool, entry: Path) -> list[str]:
    """Assemble the ``python -m PyInstaller ...`` argument list."""
    sep = ";" if platform == "windows" else ":"
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm",
        "--name", EXE_NAME,
        "--paths", str(ROOT),          # make `crude` importable from the repo
        "--distpath", str(DIST),
        "--workpath", str(BUILD),
        "--specpath", str(BUILD),      # keep the generated .spec out of the way
        "--onedir" if not onefile else "--onefile",
        "--console",
        "--collect-all", "crude",      # every phase module / binding / renderer
    ]
    if clean:
        cmd.append("--clean")

    # bundle libpd (and its siblings) under the same libs/ prefix the runtime
    # probes via sys._MEIPASS/libs
    for lib in add_libs:
        cmd += ["--add-binary", f"{lib}{sep}libs"]

    # the mingw/pywin32 shims the existing spec pinned; harmless when absent
    if platform == "windows":
        for module in ("win32timezone", "win32security", "win32gui"):
            cmd += ["--hidden-import", module]

    cmd.append(str(entry))
    return cmd


def exe_path(platform: str, onefile: bool) -> Path:
    """Where the built executable lands for the chosen bundling mode."""
    suffix = ".exe" if platform == "windows" else ""
    if onefile:
        return DIST / f"{EXE_NAME}{suffix}"
    # PyInstaller 6.x one-dir: exe at the top of the folder, internals below
    return DIST / EXE_NAME / f"{EXE_NAME}{suffix}"


def run_build(cmd: list[str], *, quiet: bool = False) -> int:
    """Run the assembled PyInstaller command, streaming its output."""
    if not quiet:
        printable = [str(Path(sys.executable).name)] + cmd[1:]
        print("[build] " + " ".join(printable))
    return subprocess.call(cmd)


def verify_exe(path: Path, *, quiet: bool = False) -> bool:
    """Prove the frozen binary starts and reaches its libraries: run --version.

    Returns ``True`` on a clean exit. The check is deliberately shallow - a real
    audio/window run needs devices - but ``--version`` still forces PyInstaller's
    import machinery to resolve the collected package, which is the part a bundle
    most often gets wrong.
    """
    if not path.is_file():
        print(f"[verify] expected executable not found at {path}", file=sys.stderr)
        return False
    if not quiet:
        print(f"[verify] running {path.name} --version")
    result = subprocess.run([str(path), "--version"],
                            capture_output=True, text=True)
    out = (result.stdout or "").strip() or (result.stderr or "").strip()
    ok = result.returncode == 0 and "crude" in out.lower()
    tag = "ok" if ok else "FAILED"
    print(f"[verify] {tag}: {out or '<no output>'} (exit {result.returncode})")
    return ok


# --------------------------------------------------------------------------
# argument handling
# --------------------------------------------------------------------------

def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="build.py",
        description="Build the crude CLI into a standalone executable "
                    "(Windows / Linux / macOS) with PyInstaller.",
    )
    parser.add_argument("--onefile", action="store_true",
                        help="single self-contained executable instead of a "
                             "one-dir folder (default: one-dir, which starts "
                             "faster and keeps libpd visible for inspection)")
    parser.add_argument("--libpd", metavar="PATH", default=None,
                        help="path to a libpd shared library (or its directory) "
                             "to stage into libs/ instead of searching")
    parser.add_argument("--skip-libs", action="store_true",
                        help="do not touch libs/; build with whatever is there")
    parser.add_argument("--no-bundle-libs", action="store_true",
                        help="do not add libs/ binaries to the bundle "
                             "(only for debugging the PyInstaller graph)")
    parser.add_argument("--clean", action="store_true",
                        help="force PyInstaller to rebuild from scratch")
    parser.add_argument("--dry-run", action="store_true",
                        help="print what would be done and exit without building")
    parser.add_argument("--verify", action="store_true",
                        help="after building, run the new binary's --version")
    parser.add_argument("-q", "--quiet", action="store_true",
                        help="less chatter")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else list(argv))
    platform = current_platform()

    def log(msg: str) -> None:
        if not args.quiet:
            print(msg)

    log(f"[platform] {platform}  (python {sys.version.split()[0]})")
    log(f"[repo]     {ROOT}")

    # dependency preflight: PyInstaller must be importable in this interpreter
    pyinstaller_ok = shutil.which("pyinstaller") or _module_present("PyInstaller")
    if not pyinstaller_ok and not args.dry_run:
        print("error: PyInstaller is not installed for this interpreter.\n"
              "       pip install -r requirements-dev.txt", file=sys.stderr)
        return 2

    # 1. make sure the shared library is staged
    try:
        ensure_library(platform, args.libpd, skip=args.skip_libs,
                       quiet=args.quiet)
    except SystemExit as exc:
        print(str(exc), file=sys.stderr)
        return 2

    add_libs = [] if args.no_bundle_libs else _bundle_files(platform)

    if not args.dry_run:
        LAUNCHER_DIR.mkdir(parents=True, exist_ok=True)
        LAUNCHER.write_text(LAUNCHER_SOURCE, encoding="utf-8")
        log(f"[entry]   generated absolute-import launcher: {LAUNCHER}")

    cmd = build_command(platform, onefile=args.onefile, add_libs=add_libs,
                        clean=args.clean, entry=LAUNCHER)

    if args.dry_run:
        log("\n[dry-run] would bundle these libs/: "
            + (", ".join(p.name for p in add_libs) or "(none)"))
        log("[dry-run] PyInstaller command:")
        print("  " + " ".join(repr(c) if " " in c else c for c in cmd))
        log(f"[dry-run] expected output: {exe_path(platform, args.onefile)}")
        return 0

    # 2. build
    rc = run_build(cmd, quiet=args.quiet)
    if rc != 0:
        print(f"error: PyInstaller exited with code {rc}", file=sys.stderr)
        return rc

    built = exe_path(platform, args.onefile)
    log(f"[build] done -> {built}")

    if not built.is_file():
        print(f"warning: expected executable not found at {built}", file=sys.stderr)
        return 1

    # 3. optional smoke test
    if args.verify:
        return 0 if verify_exe(built, quiet=args.quiet) else 1
    return 0


def _module_present(name: str) -> bool:
    import importlib.util
    return importlib.util.find_spec(name) is not None


if __name__ == "__main__":
    raise SystemExit(main())
